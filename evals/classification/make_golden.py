def main() -> None:
    ids = [e["id"] for e in EXAMPLES]
    assert len(ids) == len(set(ids)), "дублирующиеся id"
    with OUT.open("w", encoding="utf-8") as f:
        for example in EXAMPLES:
            f.write(json.dumps(example, ensure_ascii=False) + "\n")
    dev = sum(1 for e in EXAMPLES if e["split"] == "dev")
    by_imp = {i: sum(1 for e in EXAMPLES if e["expected"]["importance"] == i) for i in range(4)}
    susp = sum(1 for e in EXAMPLES if e["expected"]["suspicious"])
    print(f"{len(EXAMPLES)} примеров → {OUT.name}: dev={dev}, test={len(EXAMPLES) - dev}")
    print(f"по важности: {by_imp}, suspicious: {susp}")


if __name__ == "__main__":
    main()
